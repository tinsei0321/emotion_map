def W(ws, rows, start=1):
    """按行写入（None=空行）"""
    r = start
    for row in rows:
        if row is None:
            r += 1
            continue
        for c, v in enumerate(row, 1):
            ws.cell(row=r, column=c, value=v)
        r += 1
    return r


